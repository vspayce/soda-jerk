// Bundles the game's rules (src/game/native.js and everything it imports)
// into one script for the iOS/tvOS apps, which run it in JavaScriptCore:
//
//   npm run build:engine
//
// Writes ../apple/Shared/engine.js, exposing a global `SodaJerk`. Run it
// after changing anything in src/game; the Xcode build runs it too.
import { build } from 'esbuild'
import { fileURLToPath } from 'url'
import path from 'path'

const here = path.dirname(fileURLToPath(import.meta.url))
const outfile = path.resolve(here, '../../apple/Shared/engine.js')

await build({
  entryPoints: [path.resolve(here, '../src/game/native.js')],
  bundle: true,
  format: 'iife',
  globalName: 'SodaJerk',
  target: 'es2020',
  outfile,
  banner: { js: '// Generated by soda-jerk-web/scripts/build-engine.mjs — edit src/game, not this file.' },
  logLevel: 'warning',
})
console.log('engine bundled ->', path.relative(process.cwd(), outfile))
